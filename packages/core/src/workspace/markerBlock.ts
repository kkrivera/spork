/**
 * spork's generated content inside a file the user may also own (a root
 * `CLAUDE.md`/`AGENTS.md`, possibly pre-existing in a `workspace init`ed
 * folder) lives between these two markers. Only what's between them is ever
 * rewritten or removed — see docs/plans/0004-workspace-agent-instructions.md.
 */
export const BLOCK_BEGIN = '<!-- spork:begin (generated by spork; edits inside this block are overwritten) -->'
export const BLOCK_END = '<!-- spork:end -->'

const BEGIN_PATTERN = /<!-- spork:begin\b[^>]*-->/

interface BlockSpan {
  start: number
  end: number
}

function findBlock(text: string): BlockSpan | null {
  const begin = BEGIN_PATTERN.exec(text)
  if (!begin) return null
  const endIndex = text.indexOf(BLOCK_END, begin.index)
  if (endIndex === -1) return null
  return { start: begin.index, end: endIndex + BLOCK_END.length }
}

function wrap(body: string): string {
  return `${BLOCK_BEGIN}\n${body.trim()}\n${BLOCK_END}`
}

/**
 * Returns `existing` with spork's block set to `body`: replaced in place if
 * the markers are already there, appended after the user's own content if
 * not, or the block alone when there's no file yet (`existing === null`).
 */
export function upsertBlock(existing: string | null, body: string): string {
  if (existing === null || existing.trim() === '') return `${wrap(body)}\n`

  const span = findBlock(existing)
  if (!span) return `${existing.trimEnd()}\n\n${wrap(body)}\n`

  return `${existing.slice(0, span.start)}${wrap(body)}${existing.slice(span.end)}`
}

/**
 * Returns `existing` with spork's block removed, or `null` when nothing but
 * whitespace would be left, meaning the whole file was spork's and can be
 * deleted. A file with no block comes back unchanged.
 */
export function stripBlock(existing: string): string | null {
  const span = findBlock(existing)
  if (!span) return existing

  const before = existing.slice(0, span.start).trimEnd()
  const after = existing.slice(span.end).trim()
  const rest = [before, after].filter((part) => part !== '').join('\n\n')
  return rest === '' ? null : `${rest}\n`
}
